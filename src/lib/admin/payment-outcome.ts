/**
 * Төлбөр хоёрхон үр дүнтэй: БАТАЛГААЖСАН эсвэл АМЖИЛТГҮЙ.
 *
 * Админд «Төлбөр хүлээж байна» гэсэн гурав дахь төлөв байсан нь худлаа
 * байв: Bonum-ын нэхэмжлэх 30 минут амьдардаг (`INVOICE_TTL_SECONDS`,
 * lib/payments/bonum.ts), суудлын барьц ч 30 минут (`c_hold`, migration
 * `paid_seats`). Тэр хугацаанд төлөгдөөгүй захиалга ХЭЗЭЭ Ч төлөгдөхгүй —
 * «хүлээж» байгаа юм алга, зүгээр л бүтэлгүйтсэн. Өдрөөр «хүлээж байна»
 * гэж бичих нь ажилтанд хийх зүйл байгаа мэт санагдуулдаг (2026-10-05, эзэн
 * хоёр л сонголт харагдах ёстой гэв).
 *
 * Сүүлийн 30 минутынх нь үнэхээр явцад: хүн яг одоо төлж байж магадгүй.
 * Түүнийг «амжилтгүй» гэвэл худлаа, «хүлээж байна» гэвэл гурав дахь төлөв
 * буцаж ирнэ — тиймээс админд огт ХАРУУЛАХГҮЙ. Хагас цагийн дотор тэр нь
 * баталгаажсан эсвэл амжилтгүй болж, өөрөө гарч ирнэ.
 *
 * Өгөгдөл хөндөгдөхгүй: мөр `pending_payment` хэвээр (webhook хожуу ирвэл
 * `settle_payment` түүнийг төлөгдсөн болгож чадсаар байна). Энэ бол зөвхөн
 * АДМИНЫ дүрслэл.
 */

/** Нэхэмжлэхийн амьдрах хугацаа = суудлын барьц. Гурвуулаа нэг тоо байх ёстой. */
export const PAYMENT_WINDOW_MS = 30 * 60 * 1000

/** Төлбөр хүлээж буй мөрийн хувьд: цонх дууссан уу (амжилтгүй), явцад уу. */
export function pendingOutcome(createdAt: string, now: number): 'failed' | 'in_progress' {
  return now - new Date(createdAt).getTime() >= PAYMENT_WINDOW_MS ? 'failed' : 'in_progress'
}

/** Энэ мөрөөс өмнө үүссэн хүлээгдэж буй захиалга нь амжилтгүй. */
export function failedBefore(now: number): string {
  return new Date(now - PAYMENT_WINDOW_MS).toISOString()
}

/**
 * Админд харуулах уу. Явцад буй (сүүлийн 30 минутын) төлбөр хүлээж буй мөр
 * л нуугдана — бусад бүх төлөв хэвээр харагдана.
 */
export function visibleToAdmin(status: string, createdAt: string, now: number): boolean {
  return status !== 'pending_payment' || pendingOutcome(createdAt, now) === 'failed'
}
