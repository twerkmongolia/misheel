/**
 * Зураг байршуулах хязгаарууд — СЕРВЕР ба ХӨТӨЧ хоёрын нэг эх сурвалж.
 *
 * ── Яагаад хоёр тоо вэ ────────────────────────────────────────────────────
 * `MAX_UPLOAD_BYTES` нь БҮХ формын нийт биеийн хязгаар. Энэ нь бидний
 * сонголт биш, Next -ийн Server Action -ы тохиргоо (§ next.config.ts
 * `serverActions.bodySizeLimit`) — хүсэлт үүнээс халивал үйлдэл рүү ОГТ
 * хүрэхгүй, задлах давхаргад унана. Тэр уналтыг барих боломжгүй: доорх
 * `MAX_IMAGE_BYTES` шалгалт хүртэл ажиллахгүй.
 *
 * `MAX_IMAGE_BYTES` нь НЭГ зургийн хязгаар бөгөөд нийтээсээ БАГА байх ёстой:
 * `multipart/form-data` нь файл бүрд хилийн мөр, толгой нэмдэг ба формын
 * бусад талбарууд (нэр, тайлбар) мөн тэр биед явна. Хоёр тоо тэнцүү бол
 * зөвшөөрөгдсөн дээд хэмжээтэй зураг ҮРГЭЛЖ унана.
 */

/** Формын нийт хязгаар. `next.config.ts` -тай ЗААВАЛ тэнцүү байна. */
const MAX_UPLOAD_BYTES = 5 * 1024 * 1024

/** Нэг зураг. Нийтээс доогуур — дээрх тайлбарыг үзнэ үү. */
export const MAX_IMAGE_BYTES = 4 * 1024 * 1024

/**
 * Хилийн мөр, толгой, бусад талбаруудад үлдээх нөөц.
 *
 * Next -ийн баримт бичиг ердийн multipart -д 10-20KB зөвлөдөг. Энд 256KB:
 * барааны формд урт тайлбар, хэд хэдэн файлын толгой зэрэг орно.
 */
const OVERHEAD_BYTES = 256 * 1024

/** Хөтөч дээр шалгах нийт дээд хэмжээ. */
export const MAX_TOTAL_BYTES = MAX_UPLOAD_BYTES - OVERHEAD_BYTES

/** «4MB» гэх мэт уншигдах хэлбэр — шошго, алдааны мессежид. */
export function formatBytes(bytes: number): string {
  const mb = bytes / (1024 * 1024)
  return `${Number.isInteger(mb) ? mb : mb.toFixed(1)}MB`
}
