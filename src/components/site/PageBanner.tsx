import { PageHeader } from '@/components/ui'
import { Media, mediaExists } from './media'
import type { CSSProperties, ReactNode } from 'react'

/**
 * Хуудасны ТУУЗ — гарчиг зураг дээрээ суусан толгой хэсэг.
 *
 * ── Зураг БАЙХГҮЙ бол юу ч эвдэрэхгүй ──────────────────────────────────
 * Файл байхгүй үед хуудас өмнөх `PageHeader` -ээ хэвээр хэрэглэнэ. Хийсвэр
 * саарал орлуулагчийг тууз болгож тавих нь ХАМААГҮЙ дор: агуулгагүй том
 * зурвас нь хуудсыг нээхийн оронд хааж, «энд ямар нэг зүйл ачаалагдаагүй»
 * гэж хэлдэг. Тиймээс тууз нь ЗӨВХӨН жинхэнэ гэрэл зурагтай үедээ гарна.
 *
 * Ингэснээр ажлын урсгал маш энгийн болно: `public/media/banners/` дотор
 * зөв нэртэй файл хийхэд тухайн хуудас туузтай болно. Код засах, серверээ
 * дахин асаах шаардлагагүй.
 *
 * ── Яагаад гарчиг нь ЗҮҮН ДООД буланд вэ ───────────────────────────────
 * Сайт бүхэлдээ зүүн зэрэгцүүлэлттэй, 12 баганат тортой (§ `PageHeader`).
 * Гарчгийг зургийн голд тавих нь тухайн нэг дэлгэц дээр гоё харагдах ч
 * доор нь эхлэх агуулгатайгаа босоо тэнхлэгээ алддаг — уншигч гарчгийг
 * голоос уншаад, дараагийн мөрөө зүүн захаас хайх ёстой болно. Доод
 * зүүн булан нь тэр шугамыг хадгална: гарчиг ба доорх текст НЭГ босоо
 * шугамаас эхэлнэ.
 *
 * Уналт (`overlay`) ба текст нь ТОКЕНООС БИШ тогтмол утгаас ирнэ: уналт
 * бараан, текст цагаан. Зураг өөрөө ямар ч гэрэлтэй байж болох тул энэ хос
 * нь палитраас ХАМААРАХГҮЙ байх ёстой (§ globals.css `.scrim`).
 */
export function PageBanner({
  page,
  title,
  lead,
  eyebrow,
  fallbackSrc,
}: {
  /** `public/media/banners/<page>.jpg` — файлын нэр. */
  page: string
  title: ReactNode
  lead?: ReactNode
  eyebrow?: ReactNode
  /**
   * Хуудсанд аль хэдийн өөрийн гэсэн нээлтийн зураг байсан бол түүнийг
   * заана — тууз нь `banners/<page>.jpg` олдоогүй үед түүн рүү буцна.
   * Ингэснээр шинэ файл хийхээс өмнө ч хуудас зурагтайгаа үлдэнэ.
   */
  fallbackSrc?: string
}) {
  const preferred = `/media/banners/${page}.jpg`
  const src = mediaExists(preferred) ? preferred : (fallbackSrc ?? null)

  if (!mediaExists(src)) {
    return (
      <div className="shell pt-12 sm:pt-16">
        <PageHeader title={title} lead={lead} eyebrow={eyebrow} />
      </div>
    )
  }

  return (
    /*
      ── Зураг ба текст нь ДАВХАРГА биш ХОЁУЛАА агуулга ────────────────────
      Өмнө нь зураг тогтмол өндөртэй байж, текст нь `absolute bottom-0`
      -оор түүн дээр ХӨВДӨГ байв. Тэр нь хоёр төрлийн эвдрэл өгдөг:

        · Урт гарчиг эсвэл `lead` нь 15rem -ээс өндөр болвол текст зургаас
          ДЭЭШ халиж, наалдмал навбар руу орно (гар утсанд «Хичээл, курсын
          дэлгэрэнгүй танилцуулга» гэсэн хоёр мөр гарчиг ХАНГАЛТТАЙ).
        · Зураг өөрөө текстээс хамаарахгүй тул халилтыг зохиомж өөрөө
          «мэддэггүй» — засах цорын ганц арга нь өндрийг гараар тааруулах.

      Одоо хоёулаа НЭГ grid нүдэнд сууна. Мөрийн өндрийг хамгийн өндөр
      элемент тогтооно: текст богино бол `min-height` (хуучин clamp) хүчээ
      барина, урт бол мөр өөрөө ургаж, зураг нь `stretch` -ээр дагаж
      сунана. Халих боломж бүтцээрээ хаагдана.
    */
    <header className="relative isolate grid">
      {/* Өндөр нь ХАРЬЦААГААР биш ХЭМЖЭЭГЭЭР тогтоно. 21:9 харьцаа нь өргөн
          дэлгэцэд зөв ч утсан дээр 3см өндөр зурвас болж хувирдаг —
          зураг биш зураас. `clamp` нь хоёр туйлыг хоёуланг нь барина. */}
      {/* Параллакс: зураг нь цонхноосоо 12% ӨНДӨР бөгөөд гүйлтийн туршид
          дээшээ 7% зөөгдөнө (§ globals.css `.drift`). Хөдөлгөөн нь гүйлтэд
          ШУУД уягдсан тул JavaScript хэрэггүй, `prefers-reduced-motion`
          дээр өөрөө таслагдана.

          Тууз нь зөвхөн ЭНД хөдөлнө — хуудсан дээрх бүх зураг өөр өөр
          хурдтай хөдөлбөл гүйлт нь сэлгэцэж, унших боломжгүй болно. */}
      <div className="relative col-start-1 row-start-1 overflow-hidden">
        <div className="drift absolute inset-0 -top-[6%] h-[112%]">
          <Media
            src={src!}
            alt=""
            ratio=""
            className="h-full rounded-none"
            sizes="100vw"
            priority
            overlay
          />
        </div>
      </div>

      {/* `pt-20` — гарчиг ургахдаа дээшээ ургана. Наалдмал навбарын доогуур
          орохоос сэргийлж дээрээ зай үлдээнэ. */}
      {/*
        ⚠️ `relative z-10` нь ЧИМЭГ БИШ — ЗААВАЛ байх ёстой.

        Хоёр нүд НЭГ грид нүдэнд сууна. Зургийн сав нь `relative`, энэ нь
        байрлуулаагүй байсан: CSS -ийн зурах дараалалд байрлуулсан элемент
        нь байрлуулаагүй ах дүүгээсээ ДЭЭР зурагддаг (грид доторх зүйл нь
        `z-index` -гүй бол мөрийн блок мэт, өөрөөр хэлбэл ӨМНӨ зурагдана).
        Тиймээс гарчиг зургийн ДООР үлдэж, зураг ачаалж дуустал л
        харагдаад дараа нь бүрэн далдлагдаж байв.
      */}
      <div
        className="shell relative z-10 col-start-1 row-start-1 flex min-h-[clamp(15rem,34vw,26rem)] flex-col justify-end gap-4 pt-20 pb-8 sm:pb-11"
      >
        {/*
          Тууз нь ҮРГЭЛЖ дэлгэц нээгдмэгц харагдана — тиймээс гүйлтийн
          ажиглагчид (`data-rv`) уях нь утгагүй: ажиглагч ачаалж амжаагүй,
          эсвэл элементийг алдвал хуудасны гарчиг ҮҮРД хоосон үлдэнэ.
          Баатрын хэсэгтэй ижилхэн ЦАГААР ажилладаг цэвэр CSS хөдөлгөөн
          (§ globals.css `.enter`): JS огт оролцохгүй.
        */}
        {eyebrow && (
          <span className="enter flex items-center gap-3 text-white/70">
            <span aria-hidden className="h-px w-6 shrink-0 bg-white/40" />
            <span className="t-label">{eyebrow}</span>
          </span>
        )}
        <h1
          className="t-h1 enter max-w-[18ch] text-white"
          style={{ '--d': '80ms' } as CSSProperties}
        >
          {title}
        </h1>
        {lead && (
          <p
            className="t-lead enter max-w-[46ch] text-white/80"
            style={{ '--d': '180ms' } as CSSProperties}
          >
            {lead}
          </p>
        )}
      </div>
    </header>
  )
}
