import type { ReactNode } from 'react'

/**
 * Бүртгэлийн хэсгийн хэсгийн толгой.
 *
 * ── Яагаад `PageHeader` БИШ вэ ─────────────────────────────────────────
 * Бүртгэлийн дөрвөн хуудас бүр өөрийн нэрийг ХОЁР удаа хэлдэг байв:
 * нэг нь идэвхтэй таб дээр, нөгөө нь түүний яг доор 4rem өндөртэй `t-h1`
 * гарчиг дээр. «МИНИЙ АНГИ» дарахад «Миний анги» гэсэн асар том үг гарч
 * ирнэ — уншигчийн аль хэдийн мэдэж байгаа зүйлийг дэлгэцийн гуравны
 * нэгээр давтана.
 *
 * Гарчиг нь БҮРЭН арилахгүй: `h1` нь хуудасны бүтцийн зангуу бөгөөд дэлгэц
 * уншигч түүгээр л «би хаана байна» гэдгээ мэднэ. Зөвхөн хэмжээгээ өгнө —
 * таб нь хашгирдаг, гарчиг нь баталгаажуулна.
 *
 * `lead` нь ХАРИН үнэ цэнтэй: тэр нь табанд байхгүй мэдээлэл дамжуулна.
 */
export function Legend({
  title,
  lead,
  as: Tag = 'h2',
}: {
  title: ReactNode
  lead?: ReactNode
  /** Хуудасны толгой бол `h1`, дотоод хэсэг бол `h2` (анхдагч). */
  as?: 'h1' | 'h2'
}) {
  return (
    <header className="flex flex-col gap-3">
      <Tag className="t-h3">{title}</Tag>
      {lead && <p className="t-small max-w-[60ch] text-muted">{lead}</p>}
      <div className="hr" />
    </header>
  )
}
