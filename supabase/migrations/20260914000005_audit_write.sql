-- `audit_log` дээр RLS асаалттай атлаа ЗӨВХӨН уншихыг зөвшөөрсөн дүрэм
-- байсан (`audit_staff_read`). Бичих дүрэм огт байгаагүй тул админы үйлдэл
-- бүрийн `insert` чимээгүй татгалзагдаж, хүснэгт хоосон хэвээр байв.
--
-- Чимээгүй байсан шалтгаан: `audit()` туслах нь `insert` -ийн буцаах алдааг
-- шалгадаггүй байсан (§ actions/admin.ts — тэнд ч бас засав). Дүрэм ба код
-- хоёулаа дуугүй байсан тул хэн ч анзаараагүй.
--
-- ── Яагаад чухал вэ ───────────────────────────────────────────────────────
-- Аудит бол «хэн юуг хэзээ өөрчилсөн» гэдгийн ЦОРЫН ГАНЦ хариулт. Бараа
-- алга болсон, үнэ өөрчлөгдсөн, эрх олгогдсон — эдгээрийг хожим тайлах
-- боломж энэ хүснэгтэд л байна.

-- Зөвхөн АЖИЛТАН бичнэ: нийтийн үйлдэл (захиалга, бүртгэл) нь өөрсдийн
-- мөрөнд түүхээ үлдээдэг тул энд бичих шаардлагагүй.
drop policy if exists audit_staff_write on audit_log;
create policy audit_staff_write on audit_log
  for insert with check (public.is_staff());

