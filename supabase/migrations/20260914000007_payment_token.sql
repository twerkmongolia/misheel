-- ── Асуудал ───────────────────────────────────────────────────────────────
-- Bonum-ийн `auth/create` нь 30 минутын настай токен өгдөг АТЛАА шинэ токен
-- дахин дахин гуйхыг зөвшөөрдөггүй:
--     429 · ERROR_USE_EXISTING_TOKEN · «Use previous token»
--
-- Токеныг урьд нь Node процессын санах ойд кэшлэдэг байсан. Нэг сервер дээр
-- тэр ажиллана. Vercel дээр АЖИЛЛАХГҮЙ: хүсэлт бүр өөр instance дээр буух
-- боломжтой, instance бүр хоосон кэштэй босч, токен гуйж, 429 иднэ — тэгээд
-- нэхэмжлэл үүсэхгүй. Хэрэглэгчийн хувьд энэ нь «Төлөх» товч ажиллахгүй
-- гэсэн үг, ямар ч алдааны мэдэгдэлгүйгээр.
--
-- ── Шийдэл ────────────────────────────────────────────────────────────────
-- Токеныг өгөгдлийн санд нэг мөрөнд хадгална. Бүх instance тэр нэг мөрийг
-- уншиж, зөвхөн хугацаа нь дуусахад л шинийг гуйна.
--
-- ── Аюулгүй байдал ────────────────────────────────────────────────────────
-- Энэ токен нь merchant дансны түлхүүртэй ижил хүчтэй: түүгээр нэхэмжлэл
-- үүсгэж болно. Тиймээс RLS асаагаад ЯМАР Ч policy бичихгүй — тэгснээр
-- `anon`, `authenticated` хоёрт мөр огт байхгүй мэт харагдана. Зөвхөн
-- service-role (RLS-ийг тойрдог) хүрнэ, тэр нь зөвхөн серверийн код.

create table if not exists payment_tokens (
  provider     text primary key,
  access_token text not null,
  expires_at   timestamptz not null,
  updated_at   timestamptz not null default now()
);

alter table payment_tokens enable row level security;

-- Policy ЗОРИУД байхгүй (дээрх тайлбар). `grant` -ийг ч бас хурааж авна:
-- RLS нь `security definer` функцээр тойрогдож болдог тул хоёр давхар хаалт.
revoke all on table payment_tokens from anon, authenticated;
